package tui

// The TUI speaks the language the GUI is set to (zaidu259434 on X asked
// why it was English only). Each word it shows is a key in the table
// below, the English itself; TestEveryWordHasZh fails on one that isn't.

import "fmt"

// lang is the language the TUI speaks, set once as Run starts from the
// GUI's setting (settings.Lang, through uilang.Pick). Tests leave it "en".
var lang = "en"

// speak is the table lang reads: the TUI has Simplified Chinese only, so
// Traditional Chinese reads it too, and Japanese and German read English.
func speak(l string) string {
	if l == "zh-TW" {
		return "zh"
	}
	if _, ok := words[l]; ok {
		return l
	}
	return "en"
}

// tr is s in the TUI's language: s itself, the English, when the table
// has no word for it.
func tr(s string) string {
	if w, ok := words[lang][s]; ok {
		return w
	}
	return s
}

// trf is tr's format, filled in: the translated format keeps the
// English one's verbs (%[n]s to reorder them).
func trf(format string, args ...any) string {
	return fmt.Sprintf(tr(format), args...)
}

