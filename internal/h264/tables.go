// posClass is a raster position's column in normAdjust and quantMF.
func posClass(pos int) int {
	r, c := pos>>2, pos&3
	switch {
	case r&1 == 0 && c&1 == 0:
		return 0
	case r&1 == 1 && c&1 == 1:
		return 1
	}
	return 2
}

